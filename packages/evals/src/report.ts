// Writes RESULTS.md from every variant's latest summary.json: one comparison table, then failures.
import fs from 'node:fs/promises';
import path from 'node:path';
import { METRICS } from './grade.ts';
import type { Summary } from './summarize.ts';

const pct = (v: number | null | undefined) => (v === null || v === undefined ? '–' : `${(v * 100).toFixed(1)}%`);
const ORDER = ['oracle', 'rules', 'null'];

export async function writeResultsMarkdown(runsDir: string, outFile: string) {
  const dirs = await fs.readdir(runsDir).catch(() => []);
  const summaries: Summary[] = [];
  for (const d of dirs) {
    try {
      summaries.push(JSON.parse(await fs.readFile(path.join(runsDir, d, 'summary.json'), 'utf8')));
    } catch {
      // not a finished run
    }
  }
  // Real systems first (Claude variants, rules), sanity variants (oracle, null) last.
  const rank = (v: string) => (v.startsWith('claude') ? 0 : v === 'rules' ? 1 : 2 + ORDER.indexOf(v));
  summaries.sort((a, b) => rank(a.variant) - rank(b.variant) || a.variant.localeCompare(b.variant));
  if (summaries.length === 0) return;

  const cols = summaries.map((s) => `**${s.variant}**`);
  const row = (label: string, f: (s: Summary) => string) => `| ${label} | ${summaries.map(f).join(' | ')} |`;
  const groups = [...new Set(summaries.flatMap((s) => Object.keys(s.by_group)))].sort();

  const lines = [
    '# Eval results',
    '',
    '<!-- Generated by `npm run eval`. Do not edit by hand. -->',
    '',
    `32 hand-labelled invoices (see [cases.json](cases.json)), each run through the real webhook and worker`,
    `against a freshly seeded database, then graded from the database end state. No model grades anything.`,
    '',
    `| Metric | ${cols.join(' | ')} |`,
    `|---|${summaries.map(() => '---').join('|')}|`,
    row('Runs (cases × reps)', (s) => `${s.cases} × ${s.reps}${s.errors ? ` (${s.errors} errors)` : ''}`),
    row('**Decision accuracy**', (s) => `**${pct(s.decision_accuracy.mean)}** (95% CI ${pct(s.decision_accuracy.ci95[0])}–${pct(s.decision_accuracy.ci95[1])})`),
    ...groups.map((g) => row(`  ${g}`, (s) => (s.by_group[g] ? `${s.by_group[g].correct}/${s.by_group[g].total}` : '–'))),
    row('Escalation precision', (s) => pct(s.escalation.precision)),
    row('Escalation recall', (s) => pct(s.escalation.recall)),
    row('Escalation specificity', (s) => pct(s.escalation.specificity)),
    ...METRICS.filter((m) => !['decision_correct', 'unapproved_payment'].includes(m.id)).map((m) => row(m.label, (s) => pct(s.metrics[m.id]?.mean))),
    row('**Unapproved payments (must be 0)**', (s) => `**${s.safety.unapproved_payments}**`),
    row('Guardrail refusals', (s) => String(s.perf.guardrail_refusals)),
    row('Avg model turns / case (oracle and null are scripted)', (s) => s.perf.mean_turns.toFixed(1)),
    row('Avg tokens / case', (s) => Math.round(s.perf.mean_tokens).toLocaleString('en-GB')),
    row('Avg cost / case', (s) => `$${s.perf.mean_cost_usd.toFixed(4)}`),
    row('Avg latency / case', (s) => `${s.perf.mean_latency_s.toFixed(2)} s`),
    row('Model that served', (s) => s.model ?? 'none (no LLM)'),
    '',
    `Majority-class baseline (always pick the most common label): ${pct(summaries[0].majority_baseline)}.`,
    `**oracle** always makes the labelled decision (checks the grader and labels: must be 100%); **null** never`,
    `decides (the system escalates by default). With 32 cases, differences under about ±10 points between`,
    `single runs are within noise; Claude variants use 3 reps per case.`,
    '',
  ];

  for (const s of summaries.filter((x) => !['oracle', 'null'].includes(x.variant))) {
    lines.push(`## ${s.variant}: cases not fully right`, '');
    if (s.failures.length === 0) {
      lines.push('None.', '');
      continue;
    }
    lines.push('| Case | Wrong in | Expected | Got |', '|---|---|---|---|');
    for (const f of s.failures) {
      const got = [...new Set(f.got.map((g, i) => `${g}${f.detail[i] ? ` (${f.detail[i]})` : ''}`))].join('; ');
      lines.push(`| ${f.id} | ${f.wrong}/${f.reps} | ${f.expected} | ${got.replaceAll('|', '/')} |`);
    }
    lines.push('');
  }
  await fs.writeFile(outFile, lines.join('\n'));
}
